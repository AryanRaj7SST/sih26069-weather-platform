def run_observation_benchmark(
    scorer: ObservationScorer,
) -> Dict[str, Any]:
    """Run all 40 benchmark cases through the scorer and report metrics.

    Returns a dict with precision, recall, F1, and per-case results.
    """
    from app.intelligence.schemas import TrendAnalysisResult, TrendDirection

    results: List[Dict[str, Any]] = []
    correct = 0
    total = len(OBSERVATION_BENCHMARK_CASES)

    for case in OBSERVATION_BENCHMARK_CASES:
        # Build trend from case fields
        try:
            trend_dir = TrendDirection(case.trend_direction)
        except ValueError:
            trend_dir = TrendDirection.INSUFFICIENT_DATA

        trend = TrendAnalysisResult(
            direction=trend_dir,
            delta_value=case.trend_delta,
            rate_per_hour=case.trend_rate,
            points_count=case.trend_points,
            span_minutes=case.trend_span_minutes,
            has_data_gaps=case.trend_has_gaps,
            metric_key="water_level_m",
            station_code="CWC-TEST-STATION",
        )

        assessment = scorer.score_corroboration(
            incident_id=uuid.uuid4(),
            observation_id=uuid.uuid4(),
            incident_category=case.incident_category,
            incident_lat=case.incident_lat,
            incident_lon=case.incident_lon,
            incident_time=case.incident_time,
            incident_location_name=case.incident_location_name,
            incident_title=case.incident_title,
            incident_description=case.incident_description,
            observation_water_level_m=case.observation_water_level_m,
            observation_time=case.observation_time,
            observation_raw_metrics=case.observation_raw_metrics,
            distance_meters=case.distance_meters,
            trend=trend,
            source_type="CWC",
        )

        is_correct = assessment.relationship_type == case.expected_relationship
        if is_correct:
            correct += 1

        results.append(
            {
                "case_id": case.case_id,
                "scenario": case.scenario,
                "expected": case.expected_relationship.value,
                "actual": assessment.relationship_type.value,
                "score": assessment.overall_score,
                "correct": is_correct,
            }
        )

    # Compute metrics
    # Positive = meaningful link: CORROBORATING, CONSISTENT, WEAK, CONTRADICTORY
    # Negative = IRRELEVANT, INSUFFICIENT_DATA
    positive_relationships = {
        ObservationRelationship.CORROBORATING,
        ObservationRelationship.CONSISTENT,
        ObservationRelationship.WEAK,
        ObservationRelationship.CONTRADICTORY,
    }

    tp = sum(
        1
        for r in results
        if ObservationRelationship(r["actual"]) in positive_relationships
        and ObservationRelationship(r["expected"]) in positive_relationships
    )
    fp = sum(
        1
        for r in results
        if ObservationRelationship(r["actual"]) in positive_relationships
        and ObservationRelationship(r["expected"]) not in positive_relationships
    )
    fn = sum(
        1
        for r in results
        if ObservationRelationship(r["actual"]) not in positive_relationships
        and ObservationRelationship(r["expected"]) in positive_relationships
    )

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

    return {
        "total_cases": total,
        "correct": correct,
        "accuracy": round(correct / total, 4) if total > 0 else 0.0,
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "cases": results,
    }
